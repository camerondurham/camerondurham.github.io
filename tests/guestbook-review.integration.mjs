import assert from 'node:assert/strict';
import { test } from 'node:test';
import { spawnSync } from 'node:child_process';
import { mkdtemp, mkdir, readFile, writeFile, readdir, stat, chmod, symlink, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { onRequest } from '../functions/api/guestbook.js';
import { openLocalReview, parseReviewArgs, review } from '../scripts/guestbook-review.mjs';
import { buildGuestbookFeed, guestbookEntrySchema } from '../src/lib/guestbook.ts';

test('local D1 submit → inspect → private export/reject, with persistence and failure boundaries', { timeout: 120000 }, async () => {
  const workspace = await mkdtemp(join(tmpdir(), 'u64-review-'));
  const state = join(workspace, 'state');
  const publicDirectory = join(workspace, 'src/content/guestbook');
  const privateDirectory = join(workspace, '.wrangler/guestbook-review');
  const env = { ...process.env, GUESTBOOK_STATE_DIR: state, WRANGLER_SEND_METRICS: 'false', WRANGLER_LOG_PATH: resolve('.wrangler/logs') };
  let proxy;
  const command = (...args) => spawnSync(process.execPath, ['--experimental-strip-types', 'scripts/guestbook-review.mjs', ...args], { env, encoding: 'utf8' });
  try {
    await mkdir(publicDirectory, { recursive: true });
    const migrate = spawnSync(process.execPath, ['scripts/guestbook-wrangler.mjs', 'migrate'], { env, encoding: 'utf8' });
    assert.equal(migrate.status, 0, migrate.stdout + migrate.stderr);
    proxy = await openLocalReview(state);
    const db = proxy.env.DB;
    const operate = (...args) => review(db, parseReviewArgs(args), workspace);
    const submitted = { name: "Synthetic '); DROP TABLE guestbook_submissions;--", note: '<script>alert("x")</script> & quoted "note"\nSecond line.\u202e', model: 'Optional model', referrer: 'Private optional source' };
    const response = await onRequest({ request: new Request('http://localhost/api/guestbook', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(submitted) }), env: proxy.env });
    assert.equal(response.status, 201);
    const listed = await operate('list');
    assert.equal(listed.pending.length, 1);
    assert.deepEqual(Object.keys(listed.pending[0]), ['id', 'created_at', 'name']);
    const id = String(listed.pending[0].id);
    const inspected = await operate('inspect', id);
    for (const [key, value] of Object.entries(submitted)) assert.equal(inspected[key], value);
    assert.equal(inspected.status, 'pending');
    const args = ['export', id, '--slug', 'synthetic-review', '--published-at', '2026-11-05T12:00:00Z'];
    const dry = await operate(...args);
    assert.equal(dry.dryRun, true);
    assert.deepEqual(Object.keys(dry.entry), ['name', 'note', 'publishedAt']);
    await assert.rejects(stat(privateDirectory), { code: 'ENOENT' });
    const exported = await operate(...args, '--write');
    const file = join(workspace, exported.candidate);
    const raw = await readFile(file, 'utf8');
    const entry = JSON.parse(raw);
    assert.deepEqual(guestbookEntrySchema.parse(entry), dry.entry);
    assert.equal(entry.note, submitted.note);
    assert.doesNotMatch(raw, /<script>|\u202e/);
    assert.equal((await stat(file)).mode & 0o777, 0o600);
    assert.equal((await stat(privateDirectory)).mode & 0o777, 0o700);
    assert.deepEqual(await readdir(publicDirectory), []);
    assert.equal((await operate('inspect', id)).status, 'pending');
    assert.deepEqual(buildGuestbookFeed([], new URL('https://u64.cam')).items, [], 'private export does not enter static feed');
    await assert.rejects(operate(...args, '--write'), /already exists/);
    assert.equal(await readFile(file, 'utf8'), raw, 'retry never overwrites');
    const concurrent = await Promise.allSettled([1, 2].map(() => operate('export', id, '--slug', 'concurrent', '--published-at', '2026-11-05T12:00:00Z', '--write')));
    assert.equal(concurrent.filter(result => result.status === 'fulfilled').length, 1, 'exactly one exclusive export wins');
    assert.deepEqual(JSON.parse(await readFile(join(privateDirectory, 'concurrent.json'), 'utf8')), entry);
    const allFields = await operate('export', id, '--slug', 'optional-fields', '--published-at', '2026-11-05T12:00:00Z', '--include', 'model,referrer');
    assert.deepEqual(allFields.entry, { ...submitted, publishedAt: '2026-11-05T12:00:00Z' });

    await writeFile(join(publicDirectory, 'reviewed.json'), '{"existing":"reviewed"}');
    await assert.rejects(operate('export', id, '--slug', 'reviewed', '--published-at', '2026-11-05T12:00:00Z', '--write'), /already exists/);
    assert.equal(await readFile(join(publicDirectory, 'reviewed.json'), 'utf8'), '{"existing":"reviewed"}');
    await symlink(join(workspace, 'nonexistent'), join(privateDirectory, 'linked.json'));
    await assert.rejects(operate('export', id, '--slug', 'linked', '--published-at', '2026-11-05T12:00:00Z', '--write'), /already exists/);
    await chmod(privateDirectory, 0o500);
    await assert.rejects(operate('export', id, '--slug', 'cannot-write', '--published-at', '2026-11-05T12:00:00Z', '--write'), { code: 'EACCES' });
    await chmod(privateDirectory, 0o700);
    assert.equal((await operate('inspect', id)).status, 'pending');
    assert.ok(!(await readdir(privateDirectory)).some(name => name.startsWith('.draft-')));
    await rm(privateDirectory, { recursive: true });
    await symlink(publicDirectory, privateDirectory);
    await assert.rejects(operate(...args, '--write'), /never symlinks/);
    await rm(privateDirectory);
    await assert.rejects(operate('inspect', '99999'), /No row/);

    assert.equal((await operate('reject', id)).dryRun, true);
    assert.equal((await operate('inspect', id)).status, 'pending');
    assert.equal((await operate('reject', id, '--write')).changed, true);
    assert.equal((await operate('reject', id, '--write')).changed, false, 'safe rejection retry');
    assert.deepEqual((await operate('list')).pending, []);
    await assert.rejects(operate(...args, '--write'), /Only pending/);
    // A DB flag is not publication. It also cannot be silently overridden.
    await db.prepare("UPDATE guestbook_submissions SET status = 'published' WHERE id = ?").bind(Number(id)).run();
    await assert.rejects(operate('reject', id, '--write'), /Only pending/);
    await db.prepare("UPDATE guestbook_submissions SET status = 'pending', name = ' ' WHERE id = ?").bind(Number(id)).run();
    await assert.rejects(operate(...args, '--write'), /public entry schema/);
    await db.prepare("UPDATE guestbook_submissions SET status = 'rejected' WHERE id = ?").bind(Number(id)).run();
    for (let i = 0; i < 3; i++) await db.prepare('INSERT INTO guestbook_submissions (name, note) VALUES (?, ?)').bind(`Synthetic pagination ${i}`, 'Private fixture').run();
    const firstPage = await operate('list', '--limit', '2');
    const secondPage = await operate('list', '--limit', '2', '--before', String(firstPage.nextBefore));
    assert.equal(firstPage.pending.length, 2);
    assert.equal(secondPage.pending.length, 1);
    assert.equal(secondPage.nextBefore, null);
    assert.equal(new Set([...firstPage.pending, ...secondPage.pending].map(row => row.id)).size, 3);
    await proxy.dispose(); proxy = undefined;
    const cliInspect = command('inspect', id);
    assert.equal(cliInspect.status, 0, cliInspect.stderr);
    assert.equal(JSON.parse(cliInspect.stdout).status, 'rejected', 'CLI shares Wrangler persistence after restart');
    const cliList = command('list', '--limit', '2');
    assert.equal(cliList.status, 0, cliList.stderr);
    const cliId = String(JSON.parse(cliList.stdout).pending[0].id);
    const cliExport = command('export', cliId, '--slug', 'synthetic-cli-dry-run', '--published-at', '2026-11-05T12:00:00Z');
    assert.equal(cliExport.status, 0, cliExport.stderr);
    assert.equal(JSON.parse(cliExport.stdout).dryRun, true);
    for (const [flags, expected] of [[[], { dryRun: true }], [['--write'], { changed: true }], [['--write'], { changed: false }]]) {
      const rejected = command('reject', cliId, ...flags);
      assert.equal(rejected.status, 0, rejected.stderr);
      for (const [key, value] of Object.entries(expected)) assert.equal(JSON.parse(rejected.stdout)[key], value);
    }
    const badId = command('reject', '1 OR 1=1', '--write');
    assert.equal(badId.status, 1);
    assert.doesNotMatch(badId.stderr, /DROP TABLE|Private optional/);
    env.GUESTBOOK_STATE_DIR = join(workspace, 'unmigrated');
    const broken = command('list');
    assert.equal(broken.status, 1);
    assert.match(broken.stderr, /Local review failed/);
    assert.doesNotMatch(broken.stderr, /SELECT|no such table/);
  } finally {
    await proxy?.dispose();
    await chmod(privateDirectory, 0o700).catch(() => {});
    await rm(workspace, { recursive: true, force: true });
  }
});
